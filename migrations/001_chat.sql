-- PostgreSQL / Neon: additive chat schema. Existing project/user tables must exist.

-- Apply to the intended Neon branch before restarting the updated API.

BEGIN;

CREATE TABLE IF NOT EXISTS diagramas.conversaciones (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	proyecto_id INTEGER NOT NULL, 
	tipo VARCHAR(15) NOT NULL, 
	propietario_codigo VARCHAR(150), 
	creado_en TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_conversacion_tipo_propietario CHECK ((tipo = 'individual' AND propietario_codigo IS NOT NULL) OR (tipo = 'grupal' AND propietario_codigo IS NULL)), 
	FOREIGN KEY(proyecto_id) REFERENCES diagramas.proyecto (id) ON DELETE CASCADE ON UPDATE CASCADE, 
	FOREIGN KEY(propietario_codigo) REFERENCES "Usuario".usuarios (codigo) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_diagramas_conversaciones_propietario_codigo ON diagramas.conversaciones (propietario_codigo);

CREATE INDEX IF NOT EXISTS ix_diagramas_conversaciones_proyecto_id ON diagramas.conversaciones (proyecto_id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_conversacion_grupal ON diagramas.conversaciones (proyecto_id) WHERE tipo = 'grupal';

CREATE UNIQUE INDEX IF NOT EXISTS uq_conversacion_individual ON diagramas.conversaciones (proyecto_id, propietario_codigo) WHERE tipo = 'individual';

CREATE TABLE IF NOT EXISTS diagramas.mensajes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY, 
	conversacion_id BIGINT NOT NULL, 
	diagrama_id INTEGER, 
	rol VARCHAR(15) NOT NULL, 
	autor_codigo VARCHAR(150), 
	autor_nombre VARCHAR(250) NOT NULL, 
	texto TEXT NOT NULL, 
	resultado_ia JSONB, 
	creado_en TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL, 
	PRIMARY KEY (id), 
	CONSTRAINT ck_mensaje_rol_autor CHECK ((rol = 'user' AND autor_codigo IS NOT NULL) OR (rol = 'assistant' AND autor_codigo IS NULL)), 
	CONSTRAINT ck_mensaje_texto CHECK (length(trim(texto)) > 0), 
	FOREIGN KEY(conversacion_id) REFERENCES diagramas.conversaciones (id) ON DELETE CASCADE, 
	FOREIGN KEY(diagrama_id) REFERENCES diagramas.diagrama (id) ON DELETE SET NULL, 
	FOREIGN KEY(autor_codigo) REFERENCES "Usuario".usuarios (codigo) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_diagramas_mensajes_autor_codigo ON diagramas.mensajes (autor_codigo);

CREATE INDEX IF NOT EXISTS ix_diagramas_mensajes_diagrama_id ON diagramas.mensajes (diagrama_id);

CREATE INDEX IF NOT EXISTS ix_mensajes_conversacion_id ON diagramas.mensajes (conversacion_id, id);

COMMIT;
